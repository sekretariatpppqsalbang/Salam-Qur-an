// Generate normalized student objects with standard format wali usernames: wali.<kelas>.<nama_siswa>
export function generateInitialStudents(): Student[] {
  const students: Student[] = [];
  let counter = 1;

  for (const [className, studentNames] of Object.entries(RAW_STUDENTS_BY_CLASS)) {
    for (const name of studentNames) {
      // Create clean wali username format: wali.<kelas>.<formatted_name>
      // e.g. "wali.1A.abimanyu.fachri" or prompt format "wali.(Kelas).(Nama siswa)"
      const cleanName = name
        .toLowerCase()
        .replace(/['"]/g, '')
        .trim()
        .replace(/\s+/g, '.');
      
      const waliUsername = `wali.${className}.${cleanName}`;

      students.push({
        id: `s_${counter++}`,
        name: name,
        className: className,
        waliUsername: waliUsername
      });
    }
  }

  return students;
}

